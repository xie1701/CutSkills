STEP = 0.18


def ws(text: str, t0: float = 0.0) -> list[tuple[str, float]]:
    return [(c, round(t0 + k * STEP, 3)) for k, c in enumerate(text)]


def chain(parts, t0: float = 0.0) -> list[tuple[str, float]]:
    """parts = [(文本, 说完这一截之后再停几秒), ...]，停的数字就是量出来的词间距。"""
    out, t = [], t0
    for txt, gap in parts:
        for c in txt:
            out.append((c, round(t, 3)))
            t += STEP
        t = t - STEP + gap
    return out


def hits(words) -> list[str]:
    """照 audit() 的扫法走：每个 ≥PITCH_GAP 的停顿都问一次，命中就停。"""
    for k in range(len(words) - 1):
        gap = words[k + 1][1] - words[k][1]
        if gap < EA.PITCH_GAP:
            continue
        unit = EA.prompt_restart(words, k)
        if unit:
            return [unit]
    return []


